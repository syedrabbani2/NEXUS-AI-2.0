
from datetime import datetime
from typing import Any


def build_research_report(
    question: str,
    answer: str,
    sources: list[dict[str, Any]],
    citation_report: dict[str, Any] | None = None
) -> dict[str, Any]:
    """Build a structured research report from NEXUS results."""

    citation_report = citation_report or {}

    return {
        "title": "NEXUS AI Research Report",
        "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "question": question,
        "answer": answer,
        "total_sources": len(sources),
        "citation_report": citation_report,
        "sources": sources
    }


def generate_markdown_report(report: dict[str, Any]) -> str:
    """Convert a NEXUS research report into Markdown."""

    lines = [
        f"# {report.get('title', 'Research Report')}",
        "",
        f"**Generated:** {report.get('generated_at', 'Not available')}",
        "",
        "## Research Question",
        "",
        report.get("question", ""),
        "",
        "## Executive Answer",
        "",
        report.get("answer", ""),
        "",
        "## Claim-Level Evidence Analysis",
        ""
    ]

    citation_report = report.get("citation_report", {})

    for claim in citation_report.get("claims", []):
        lines.extend([
            f"### {claim.get('claim_id', 'Claim')}",
            "",
            claim.get("claim", ""),
            "",
            f"**Status:** {claim.get('verification_status', 'unverified')}",
            f"**Evidence relevance:** {claim.get('best_evidence_score', 0):.1%}",
            ""
        ])

        for evidence in claim.get("evidence_matches", []):
            lines.extend([
                f"- **{evidence.get('source_id', 'Source')}:** "
                f"{evidence.get('source_name', 'Unknown')}",
                f"  - Evidence: {evidence.get('evidence', '')}",
                ""
            ])

    lines.extend([
        "## Source References",
        ""
    ])

    for index, source in enumerate(report.get("sources", []), start=1):
        lines.extend([
            f"### Source {index}: {source.get('file', 'Unknown source')}",
            f"- Type: {source.get('source_type', 'Unknown')}",
            f"- Page: {source.get('page', 'Unknown')}",
            f"- Row: {source.get('row', 'Unknown')}",
            f"- Sheet: {source.get('sheet', 'Not available')}",
        ])

        if source.get("url"):
            lines.append(f"- URL: {source['url']}")

        if source.get("preview"):
            lines.append(f"- Preview: {source['preview']}")

        lines.append("")

    lines.extend([
        "---",
        "",
        "*Generated by NEXUS AI 2.0. Evidence relevance scores represent "
        "lexical overlap and do not independently establish factual accuracy.*"
    ])

    return "\n".join(lines)
