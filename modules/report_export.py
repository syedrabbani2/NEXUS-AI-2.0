
import csv
import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def generate_pdf_report(report: dict) -> bytes:
    """Generate a downloadable PDF research report."""

    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        spaceAfter=16
    )

    body_style = styles["BodyText"]
    heading_style = styles["Heading2"]

    story = []

    def safe_text(value):
        return escape(str(value or "")).replace("\n", "<br/>")

    story.append(
        Paragraph(
            safe_text(report.get("title", "NEXUS AI Research Report")),
            title_style
        )
    )

    story.append(
        Paragraph(
            f"<b>Generated:</b> "
            f"{safe_text(report.get('generated_at', 'Not available'))}",
            body_style
        )
    )

    story.append(Spacer(1, 12))

    story.append(Paragraph("Research Question", heading_style))
    story.append(Paragraph(
        safe_text(report.get("question", "")),
        body_style
    ))

    story.append(Spacer(1, 12))

    story.append(Paragraph("Executive Answer", heading_style))
    story.append(Paragraph(
        safe_text(report.get("answer", "")),
        body_style
    ))

    citation_report = report.get("citation_report", {})

    story.append(Spacer(1, 12))
    story.append(Paragraph("Claim-Level Evidence Analysis", heading_style))

    story.append(Paragraph(
        "Evidence relevance scores represent lexical overlap, "
        "not confirmed factual accuracy.",
        body_style
    ))

    for claim in citation_report.get("claims", []):
        story.append(Spacer(1, 8))

        story.append(Paragraph(
            f"<b>{safe_text(claim.get('claim_id', 'Claim'))}</b>",
            body_style
        ))

        story.append(Paragraph(
            safe_text(claim.get("claim", "")),
            body_style
        ))

        story.append(Paragraph(
            f"Status: {safe_text(claim.get('verification_status'))} | "
            f"Evidence relevance: "
            f"{float(claim.get('best_evidence_score', 0)):.1%}",
            body_style
        ))

        for evidence in claim.get("evidence_matches", []):
            story.append(Paragraph(
                f"<b>{safe_text(evidence.get('source_id'))}: "
                f"{safe_text(evidence.get('source_name'))}</b>",
                body_style
            ))

            story.append(Paragraph(
                safe_text(evidence.get("evidence", "")),
                body_style
            ))

    story.append(Spacer(1, 12))
    story.append(Paragraph("Source References", heading_style))

    for index, source in enumerate(report.get("sources", []), start=1):
        source_name = source.get(
            "file",
            source.get("source_name", "Unknown source")
        )

        details = [
            f"<b>Source {index}: {safe_text(source_name)}</b>",
            f"Type: {safe_text(source.get('source_type', 'Unknown'))}",
            f"Page: {safe_text(source.get('page', 'Unknown'))}",
            f"Row: {safe_text(source.get('row', 'Unknown'))}",
            f"Sheet: {safe_text(source.get('sheet', 'Not available'))}"
        ]

        if source.get("url"):
            details.append(f"URL: {safe_text(source['url'])}")

        story.append(Paragraph("<br/>".join(details), body_style))
        story.append(Spacer(1, 8))

    story.append(Spacer(1, 12))
    story.append(Paragraph(
        "<i>Generated by NEXUS AI 2.0. "
        "Evidence relevance does not independently establish factual accuracy.</i>",
        body_style
    ))

    doc.build(story)

    return buffer.getvalue()


def generate_csv_report(report: dict) -> bytes:
    """Generate a downloadable claim and evidence CSV."""

    buffer = io.StringIO()

    fieldnames = [
        "claim_id",
        "claim",
        "verification_status",
        "best_evidence_score",
        "source_id",
        "source_name",
        "evidence_relevance",
        "evidence"
    ]

    writer = csv.DictWriter(
        buffer,
        fieldnames=fieldnames
    )

    writer.writeheader()

    citation_report = report.get("citation_report", {})

    for claim in citation_report.get("claims", []):

        matches = claim.get("evidence_matches", [])

        if not matches:
            writer.writerow({
                "claim_id": claim.get("claim_id", ""),
                "claim": claim.get("claim", ""),
                "verification_status": claim.get(
                    "verification_status", "unverified"
                ),
                "best_evidence_score": claim.get(
                    "best_evidence_score", 0
                )
            })

        for evidence in matches:
            writer.writerow({
                "claim_id": claim.get("claim_id", ""),
                "claim": claim.get("claim", ""),
                "verification_status": claim.get(
                    "verification_status", "unverified"
                ),
                "best_evidence_score": claim.get(
                    "best_evidence_score", 0
                ),
                "source_id": evidence.get("source_id", ""),
                "source_name": evidence.get("source_name", ""),
                "evidence_relevance": evidence.get(
                    "relevance_score", 0
                ),
                "evidence": evidence.get("evidence", "")
            })

    return buffer.getvalue().encode("utf-8-sig")
