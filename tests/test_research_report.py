
from datetime import datetime

from modules.research_report import (
    build_research_report,
    generate_markdown_report,
)


def test_build_research_report_creates_expected_structure():
    report = build_research_report(
        "What is RAG?",
        "RAG combines retrieval and generation.",
        [{"file": "rag.pdf"}],
    )

    assert report["title"] == "NEXUS AI Research Report"
    assert report["question"] == "What is RAG?"
    assert report["answer"] == "RAG combines retrieval and generation."
    assert report["total_sources"] == 1
    assert report["sources"] == [{"file": "rag.pdf"}]
    assert report["citation_report"] == {}


def test_build_research_report_generates_valid_timestamp():
    report = build_research_report("Question", "Answer", [])

    parsed = datetime.strptime(
        report["generated_at"], "%Y-%m-%d %H:%M:%S"
    )

    assert parsed is not None


def test_build_research_report_preserves_citation_report():
    citations = {"claims": [{"claim_id": "C1"}]}

    report = build_research_report(
        "Question", "Answer", [], citations
    )

    assert report["citation_report"] == citations


def test_build_research_report_handles_empty_sources():
    report = build_research_report("Question", "Answer", [])

    assert report["total_sources"] == 0
    assert report["sources"] == []


def test_generate_markdown_report_contains_main_sections():
    report = build_research_report(
        "What is RAG?",
        "RAG retrieves relevant information.",
        [],
    )

    markdown = generate_markdown_report(report)

    assert "# NEXUS AI Research Report" in markdown
    assert "## Research Question" in markdown
    assert "## Executive Answer" in markdown
    assert "## Claim-Level Evidence Analysis" in markdown
    assert "## Source References" in markdown


def test_generate_markdown_report_includes_claim_and_evidence():
    report = {
        "citation_report": {
            "claims": [
                {
                    "claim_id": "C1",
                    "claim": "RAG uses retrieval.",
                    "verification_status": "supported",
                    "best_evidence_score": 0.85,
                    "evidence_matches": [
                        {
                            "source_id": "S1",
                            "source_name": "rag.pdf",
                            "evidence": "Relevant retrieved evidence.",
                        }
                    ],
                }
            ]
        }
    }

    markdown = generate_markdown_report(report)

    assert "### C1" in markdown
    assert "RAG uses retrieval." in markdown
    assert "**Status:** supported" in markdown
    assert "**Evidence relevance:** 85.0%" in markdown
    assert "S1" in markdown
    assert "Relevant retrieved evidence." in markdown


def test_generate_markdown_report_includes_source_metadata():
    report = {
        "sources": [
            {
                "file": "report.pdf",
                "source_type": "document",
                "page": 5,
                "row": 2,
                "sheet": "Sheet1",
                "url": "https://example.com",
                "preview": "Sample preview",
            }
        ]
    }

    markdown = generate_markdown_report(report)

    assert "Source 1: report.pdf" in markdown
    assert "Type: document" in markdown
    assert "Page: 5" in markdown
    assert "Row: 2" in markdown
    assert "Sheet: Sheet1" in markdown
    assert "URL: https://example.com" in markdown
    assert "Preview: Sample preview" in markdown


def test_generate_markdown_report_handles_empty_report():
    markdown = generate_markdown_report({})

    assert "# Research Report" in markdown
    assert "## Research Question" in markdown
    assert "## Source References" in markdown
    assert "Generated by NEXUS AI 2.0" in markdown


def test_generate_markdown_report_uses_default_claim_values():
    report = {
        "citation_report": {
            "claims": [
                {
                    "claim": "A claim without an ID.",
                    "evidence_matches": [],
                }
            ]
        }
    }

    markdown = generate_markdown_report(report)

    assert "### Claim" in markdown
    assert "**Status:** unverified" in markdown
    assert "**Evidence relevance:** 0.0%" in markdown


def test_generate_markdown_report_uses_default_source_values():
    report = {"sources": [{}]}

    markdown = generate_markdown_report(report)

    assert "Source 1: Unknown source" in markdown
    assert "Type: Unknown" in markdown
    assert "Page: Unknown" in markdown
    assert "Row: Unknown" in markdown
    assert "Sheet: Not available" in markdown
